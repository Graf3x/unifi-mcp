<#
Dev-only tool: draws the connector icons and writes src/UnifiMcp/Connector/IconData.cs (base64 PNG constants).
Fleet's deploy_app cannot carry binary files, so the PNGs live in the source as text. Re-run after changing the artwork:
    pwsh tools/make-icons.ps1
Each size is drawn natively (not scaled down) so the 32 px one stays crisp. Windows only (System.Drawing).
#>
Add-Type -AssemblyName System.Drawing

$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root 'src/UnifiMcp/Connector/IconData.cs'

function New-Icon([int]$size) {
    $bmp = New-Object System.Drawing.Bitmap $size, $size, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $g.Clear([System.Drawing.Color]::Transparent)

    # Solid rounded square.
    $r = [single]($size * 0.22)
    $d = $r * 2
    $path = New-Object System.Drawing.Drawing2D.GraphicsPath
    $path.AddArc(0, 0, $d, $d, 180, 90)
    $path.AddArc($size - $d, 0, $d, $d, 270, 90)
    $path.AddArc($size - $d, $size - $d, $d, $d, 0, 90)
    $path.AddArc(0, $size - $d, $d, $d, 90, 90)
    $path.CloseFigure()
    $bg = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 0x0B, 0x5F, 0xD6))
    $g.FillPath($bg, $path)

    # A signal glyph: a dot with three arcs rising from it (an access point / antenna).
    $white = [System.Drawing.Color]::White
    $cx = $size * 0.5
    $cy = $size * 0.69
    $w = [single]($size * 0.075)
    $pen = New-Object System.Drawing.Pen $white, $w
    $pen.StartCap = [System.Drawing.Drawing2D.LineCap]::Round
    $pen.EndCap = [System.Drawing.Drawing2D.LineCap]::Round
    foreach ($f in 0.17, 0.30, 0.43) {
        $rad = $size * $f
        $g.DrawArc($pen, [single]($cx - $rad), [single]($cy - $rad), [single](2 * $rad), [single](2 * $rad), 227, 86)
    }
    $dot = $size * 0.075
    $g.FillEllipse((New-Object System.Drawing.SolidBrush $white), [single]($cx - $dot), [single]($cy - $dot), [single](2 * $dot), [single](2 * $dot))
    $g.Dispose()

    $ms = New-Object System.IO.MemoryStream
    $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    return $ms.ToArray()
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated by tools/make-icons.ps1; edit the script, not this file.>')
[void]$sb.AppendLine('namespace UnifiMcp;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// <summary>The connector icons as base64 PNG (Fleet''s deploy_app cannot carry binary files). Served at /mcp/icon-{size}.png.</summary>')
[void]$sb.AppendLine('public static class IconData')
[void]$sb.AppendLine('{')
foreach ($size in 512, 180, 32) {
    $bytes = New-Icon $size
    Write-Host "icon-$size.png: $($bytes.Length) bytes"
    [void]$sb.AppendLine("    public const string Icon$size =")
    [void]$sb.AppendLine('        "' + [Convert]::ToBase64String($bytes) + '";')
    [void]$sb.AppendLine('')
}
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Host "wrote $out"
